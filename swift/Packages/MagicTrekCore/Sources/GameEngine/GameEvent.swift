import CardKit

/// What happened, for the log and for animating the table. Objects are referenced by id; the UI
/// resolves names through the state and card database.
public enum GameEvent: Codable, Hashable, Sendable {
    case gameStarted(first: PlayerID)
    case turnBegan(turn: Int, player: PlayerID)
    case phase(Phase)
    case drew(player: PlayerID, count: Int)
    case mulliganed(player: PlayerID, to: Int)
    case playedLand(player: PlayerID, object: ObjectID)
    case cast(player: PlayerID, object: ObjectID, kicked: Bool)
    case entered(object: ObjectID)
    case tokenCreated(player: PlayerID, object: ObjectID)
    case tapped(object: ObjectID)
    case untapped(object: ObjectID)
    case damage(to: ObjectID, amount: Int, source: ObjectID?)         // to: object or player object
    case lifeChanged(player: PlayerID, delta: Int)
    case died(object: ObjectID)
    case exiled(object: ObjectID)
    case bounced(object: ObjectID)
    case destroyed(object: ObjectID)
    case discarded(player: PlayerID, object: ObjectID)
    case milled(player: PlayerID, object: ObjectID)
    case counters(object: ObjectID, kind: CounterKind, delta: Int)
    case attackersDeclared(player: PlayerID, attackers: [ObjectID])
    case blockersDeclared(player: PlayerID, blocks: [ObjectID: ObjectID])
    case triggered(object: ObjectID, text: String)
    case activated(object: ObjectID, text: String)
    case stationed(spacecraft: ObjectID, by: ObjectID, counters: Int)
    case becameCreature(object: ObjectID)
    case equipped(equipment: ObjectID, to: ObjectID)
    case fought(a: ObjectID, b: ObjectID)
    case searched(player: PlayerID, object: ObjectID?)
    case surveilled(player: PlayerID, graveyard: Int, top: Int)
    case explored(creature: ObjectID, landFound: Bool)
    case assimilated(object: ObjectID, by: PlayerID)
    case sagaChapter(object: ObjectID, chapter: Int)
    case conceded(player: PlayerID)
    case gameOver(winner: PlayerID, reason: String)
    case note(String)
}
