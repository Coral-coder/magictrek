    signingConfigs {
        // Release signing comes from the environment (CI secrets); without it the debug key is
        // used so a sideloadable APK always builds.
        create("release") {
            val storePath = System.getenv("ANDROID_KEYSTORE_PATH")
            if (storePath != null && file(storePath).exists()) {
                storeFile = file(storePath)
                storePassword = System.getenv("ANDROID_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("ANDROID_KEY_ALIAS")
                keyPassword = System.getenv("ANDROID_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            val hasStore = System.getenv("ANDROID_KEYSTORE_PATH")?.let { file(it).exists() } ?: false
            signingConfig = if (hasStore) signingConfigs.getByName("release") else signingConfigs.getByName("debug")
        }
    }
